#!/usr/bin/env python3
"""Cross-section-shape study: rectangular vs hexagonal twisted CNT-bundle tension.

Both curves are read from real run output (no pasted literals):
- hex  (reference): fiber_model/hex_cross_section/stress_strain_gage.dat
- rect (this work): fiber_model/rect_cross_section/stress_strain_gage_rect.dat

Both runs use a byte-identical tension deck (same FF, grips, gage, deform
protocol, box) and a bundle of exactly 92 chains x 407 beads; the only
difference is the in-plane packing of the chain axes.

Two quirks of the shared deck, preserved deliberately so the two runs stay
comparable, are corrected here at analysis time:

1. ``variable Lz0 equal lz`` is a *deferred* equal-style variable, so
   ``(lz-v_Lz0)/v_Lz0`` evaluates to 0 at every step -- the v_strain column is
   identically zero in BOTH datasets. Engineering strain is therefore
   reconstructed from the known protocol: ``fix deform ... z erate 2.0e-6``
   with ``timestep 1.0`` starting at step 20000.

2. The gage stress carries a large twist-induced residual at zero strain, so
   the modulus is fitted on the baseline-subtracted curve.
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.path.insert(0, str(REPO))

HEX_DAT = HERE / "fiber_model/hex_cross_section/stress_strain_gage.dat"
RECT_DAT = HERE / "fiber_model/rect_cross_section/stress_strain_gage_rect.dat"
OUT_PNG = HERE / "fiber_model/rect_cross_section/overlay_rect_vs_hex.png"
OUT_MD = HERE / "fiber_model/rect_cross_section/overlay_rect_metrics.md"

BAR_TO_GPA = 1e-4  # same convention as compare_demo1.py
ERATE = 2.0e-6  # 1/fs, from `fix f_def all deform 1 z erate 2.0e-6`
DT = 1.0  # fs, from `timestep 1.0`
STEP0 = 20000  # deform starts after the 20000-step NVT equilibration


def read_curve(path: Path) -> tuple[list[float], list[float]]:
    """Return (strain, stress_GPa) with strain rebuilt from the step number."""
    strain: list[float] = []
    stress: list[float] = []
    for line in path.read_text().splitlines():
        if line.lstrip().startswith("#") or not line.strip():
            continue
        try:
            step, _, szz, *_ = (float(p) for p in line.split())
        except ValueError:
            continue
        strain.append(ERATE * DT * max(step - STEP0, 0.0))
        stress.append(szz * BAR_TO_GPA)
    return strain, stress


def fit_modulus(strain: list[float], stress: list[float], emax: float) -> float:
    """|d(sigma)/d(epsilon)| by least squares over strain <= emax, in GPa."""
    pts = [(e, s) for e, s in zip(strain, stress) if e <= emax]
    n = len(pts)
    mean_e = sum(e for e, _ in pts) / n
    mean_s = sum(s for _, s in pts) / n
    cov = sum((e - mean_e) * (s - mean_s) for e, s in pts)
    var = sum((e - mean_e) ** 2 for e, _ in pts)
    return abs(cov / var)


def main() -> int:
    curves = {}
    for label, path in (("hex", HEX_DAT), ("rect", RECT_DAT)):
        e, s = read_curve(path)
        s0 = s[0]
        curves[label] = {
            "strain": e,
            "stress": s,
            "delta": [v - s0 for v in s],
            "residual": s0,
            "n": len(e),
            "path": path,
        }

    emax = min(max(c["strain"]) for c in curves.values())
    for c in curves.values():
        c["E"] = fit_modulus(c["strain"], c["delta"], emax)

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 4.5))
    styles = {"hex": ("tab:blue", "-", "hexagonal (reference)"),
              "rect": ("tab:red", "--", "rectangular 12x8-4 (this work)")}
    for label, c in curves.items():
        col, ls, name = styles[label]
        ax1.plot(c["strain"], c["stress"], ls, color=col, label=name)
        ax2.plot(c["strain"], c["delta"], ls, color=col,
                 label=f"{name}\n|E| = {c['E']:.2f} GPa")
    ax1.set_title("Gage stress (raw, incl. twist residual)")
    ax2.set_title("Baseline-subtracted, with fitted slope")
    for ax in (ax1, ax2):
        ax.set_xlabel("engineering strain (reconstructed)")
        ax.set_ylabel(r"$\sigma_{zz}$ gage [GPa]")
        ax.grid(alpha=0.3)
        ax.legend(fontsize=8)
    fig.suptitle("Twisted CNT bundle, 92 chains: cross-section shape comparison")
    fig.tight_layout()
    fig.savefig(OUT_PNG, dpi=150)

    h, r = curves["hex"], curves["rect"]
    lines = [
        "# Rect-vs-hex overlay metrics (generated by compare_rect.py)",
        "",
        f"- hex data:  `{h['path']}` ({h['n']} points)",
        f"- rect data: `{r['path']}` ({r['n']} points)",
        f"- strain reconstructed as erate*dt*(step-{STEP0}), "
        f"erate={ERATE}/fs, dt={DT} fs (the v_strain column is identically "
        "zero in BOTH datasets -- deferred `variable Lz0 equal lz`)",
        f"- fit window: strain <= {emax:.4f}",
        "",
        "| quantity | hex | rect |",
        "| --- | --- | --- |",
        f"| zero-strain gage stress (GPa) | {h['residual']:.4f} | {r['residual']:.4f} |",
        f"| stress change over window (GPa) | {h['delta'][-1]:.4f} | {r['delta'][-1]:.4f} |",
        f"| fitted |E| (GPa) | {h['E']:.3f} | {r['E']:.3f} |",
        "",
        f"**Rect/hex modulus ratio: {r['E'] / h['E']:.3f}**",
        "",
        f"Overlay figure: `{OUT_PNG.name}`",
    ]
    OUT_MD.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
