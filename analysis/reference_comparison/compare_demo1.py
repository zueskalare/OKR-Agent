#!/usr/bin/env python3
"""Demo1 (twisted CNT bundle tension): agent-vs-reference stress-strain overlay.

Reads BOTH curves from the actual data files (no pasted literals):
- agent:     jobs/session-atomagent-demo1/output/stress.dat        (TimeStep, v_szz [bar], v_strain)
- reference: reference_comparison/fiber_model/hex_cross_section/stress_strain_gage.dat
             (TimeStep, v_strain, v_szz_gage [bar], v_tempv, v_pzzv)

The agent dataset is run through the validation gates and the verdict is
stamped onto the figure — the archived demo1 data comes from a run with no
time integrator whose stress was harvested from a blown-up build run, so the
overlay documents the failure; the paper number needs a re-run on the fixed
harness.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.path.insert(0, str(REPO))

from AtomAgents.utils.run_validation import validate_stress_strain, format_verdict_markdown  # noqa: E402

# OKR_RUNS_ROOT points the overlay at another runs/ tree (the published sessions
# live in the dataset: huggingface.co/datasets/BioDMX-UGA/OKRAgent_runs).
RUNS = Path(os.environ.get("OKR_RUNS_ROOT", REPO / "runs"))
AGENT_DAT = RUNS / "jobs/session-atomagent-demo1/output/stress.dat"
REF_DAT = HERE / "fiber_model/hex_cross_section/stress_strain_gage.dat"
OUT_PNG = HERE / "fiber_model/hex_cross_section/overlay_demo1.png"
OUT_MD = HERE / "fiber_model/hex_cross_section/overlay_demo1_metrics.md"

BAR_TO_GPA = 1e-4


def read_columns(path: Path, cols: dict[str, int]) -> dict[str, list[float]]:
    out: dict[str, list[float]] = {k: [] for k in cols}
    for line in path.read_text().splitlines():
        if line.lstrip().startswith("#") or not line.strip():
            continue
        parts = line.split()
        try:
            values = [float(p) for p in parts]
        except ValueError:
            continue
        for name, idx in cols.items():
            if idx < len(values):
                out[name].append(values[idx])
    return out


def main() -> int:
    agent = read_columns(AGENT_DAT, {"stress_bar": 1, "strain": 2})
    ref = read_columns(REF_DAT, {"strain": 1, "stress_bar": 2})

    a_strain = agent["strain"]
    a_stress = [s * BAR_TO_GPA for s in agent["stress_bar"]]
    r_strain = ref["strain"]
    r_stress = [s * BAR_TO_GPA for s in ref["stress_bar"]]

    verdict = validate_stress_strain(a_strain, a_stress)
    a_max = max(abs(s) for s in a_stress)
    r_max = max(abs(s) for s in r_stress)

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 4.5))
    for ax in (ax1, ax2):
        ax.plot(r_strain, r_stress, label="Reference (hex fiber, gage)", lw=1.5)
        ax.plot(a_strain, a_stress, label="Agent (demo1 archive)", lw=1.2, ls="--")
        ax.set_xlabel("engineering strain")
        ax.set_ylabel(r"$\sigma_{zz}$ [GPa]")
    ax1.set_title("full range (agent run diverges)")
    lim = 1.5 * max(abs(min(r_stress)), abs(max(r_stress)))
    ax2.set_ylim(-lim, lim)
    ax2.set_title("zoom to reference scale")
    ax1.legend(fontsize=8)
    fig.suptitle(
        f"Demo1 CNT tension — agent data verdict: {verdict['overall']} "
        f"(agent max |σ| = {a_max:.3g} GPa vs reference {r_max:.3g} GPa)"
    )
    fig.tight_layout()
    OUT_PNG.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT_PNG, dpi=200)

    OUT_MD.write_text(
        "# Demo1 overlay metrics (generated by compare_demo1.py)\n\n"
        f"- agent data: `{AGENT_DAT}` ({len(a_strain)} points)\n"
        f"- reference data: `{REF_DAT}` ({len(r_strain)} points)\n"
        f"- agent max |stress|: {a_max:.6g} GPa\n"
        f"- reference max |stress|: {r_max:.6g} GPa\n\n"
        + format_verdict_markdown(verdict)
        + "\n\n**Conclusion:** the archived agent dataset is physically invalid "
        "(harvested from a blown-up run executed without a time integrator); "
        "the overlay documents the failure mode. Re-run demo1 on the fixed "
        "harness before quoting agent numbers.\n"
    )
    print(f"wrote {OUT_PNG}\nwrote {OUT_MD}\nverdict: {verdict['overall']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
