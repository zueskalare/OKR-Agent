#!/usr/bin/env python3
"""Demo2 (polycrystalline bcc Fe compression): agent-vs-reference overlay.

Reads BOTH curves from the actual files (no pasted literals):
- agent:     jobs_bk_2/session-atomagent-demo2_success_1/post/{strain,stress}.dat
             (single-column files; strain negative under compression, stress GPa)
- reference: reference_comparison/multi_grain_model/build.log — the in-script
             `log build.log` redirect holds the compression thermo block
             (Step Temp PotEng TotEng Press Pzz v_sigma_zz Lx Ly Lz Atoms);
             strain = 1 - Lz/Lz0, stress = Pzz [bar] → GPa.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.path.insert(0, str(REPO))

from AtomAgents.utils.run_validation import validate_stress_strain, format_verdict_markdown  # noqa: E402

# OKR_RUNS_ROOT points the overlay at another runs/ tree (the published sessions
# live in the dataset: huggingface.co/datasets/BioDMX-UGA/OKRAgent_runs).
RUNS = Path(os.environ.get("OKR_RUNS_ROOT", REPO / "runs"))
AGENT_DIR = RUNS / "archive/jobs_bk_2/session-atomagent-demo2_success_1/post"
REF_LOG = HERE / "multi_grain_model/build.log"
OUT_PNG = HERE / "multi_grain_model/overlay_demo2.png"
OUT_MD = HERE / "multi_grain_model/overlay_demo2_metrics.md"

BAR_TO_GPA = 1e-4


def read_single_column(path: Path) -> list[float]:
    values = []
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        try:
            values.append(float(line))
        except ValueError:
            continue
    return values


def read_reference_compression(log_path: Path) -> tuple[list[float], list[float]]:
    """Extract (strain, stress_GPa) from the compression thermo segment."""
    strain: list[float] = []
    stress: list[float] = []
    headers: list[str] = []
    in_segment = False
    lz0 = None
    for line in log_path.read_text(errors="replace").splitlines():
        stripped = line.strip()
        if stripped.startswith("Step") and "v_sigma_zz" in stripped:
            headers = stripped.split()
            in_segment = True
            continue
        if in_segment:
            parts = stripped.split()
            if len(parts) != len(headers):
                if stripped.startswith(("Loop time", "WARNING", "ERROR")):
                    in_segment = False
                continue
            try:
                row = dict(zip(headers, (float(p) for p in parts)))
            except ValueError:
                in_segment = False
                continue
            lz = row["Lz"]
            if lz0 is None:
                lz0 = lz
            strain.append(1.0 - lz / lz0)
            stress.append(row["Pzz"] * BAR_TO_GPA)
    return strain, stress


def main() -> int:
    a_strain_raw = read_single_column(AGENT_DIR / "strain.dat")
    a_stress = read_single_column(AGENT_DIR / "stress.dat")
    n = min(len(a_strain_raw), len(a_stress))
    a_strain = [abs(s) for s in a_strain_raw[:n]]
    a_stress = a_stress[:n]

    r_strain, r_stress = read_reference_compression(REF_LOG)

    verdict = validate_stress_strain(a_strain, a_stress)

    fig, ax = plt.subplots(figsize=(7, 5))
    ax.plot(r_strain, r_stress, label="Reference (150 Å polycrystal, Pzz)", lw=1.5)
    ax.plot(a_strain, a_stress, label="Agent (demo2_success_1, 100 Å pilot)", lw=1.2, ls="--")
    ax.set_xlabel("|engineering strain|")
    ax.set_ylabel(r"$\sigma_{zz}$ [GPa] (compressive positive)")
    ax.set_title(
        f"Demo2 Fe compression — agent data verdict: {verdict['overall']}"
    )
    ax.legend(fontsize=9)
    ax.grid(alpha=0.3)
    fig.tight_layout()
    OUT_PNG.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT_PNG, dpi=200)

    a_max = max(a_stress) if a_stress else float("nan")
    r_max = max(r_stress) if r_stress else float("nan")
    OUT_MD.write_text(
        "# Demo2 overlay metrics (generated by compare_demo2.py)\n\n"
        f"- agent data: `{AGENT_DIR}/stress.dat` + `strain.dat` ({n} points)\n"
        f"- reference data: `{REF_LOG}` compression segment ({len(r_strain)} points)\n"
        f"- agent stress at zero strain: {a_stress[0]:.4g} GPa\n"
        f"- reference stress at zero strain: {r_stress[0]:.4g} GPa\n"
        f"- agent max stress: {a_max:.4g} GPa\n"
        f"- reference max stress: {r_max:.4g} GPa\n\n"
        + format_verdict_markdown(verdict)
        + "\n\n**Notes:** the agent run used a downscoped 100 Å pilot "
        "(303k→113k atoms after an MPI failure) while the reference compresses "
        "the full 150 Å model; BOTH curves start from a non-zero compressive "
        "stress at ε=0 (neither system was relaxed to zero pressure before "
        "loading), so absolute magnitudes carry that offset.\n"
    )
    print(f"wrote {OUT_PNG}\nwrote {OUT_MD}\nverdict: {verdict['overall']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
